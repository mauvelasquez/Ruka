// ── HELPERS ───────────────────────────────────────────────────────────────────

// Obtener banner aleatorio
export function getRandomBanner() {
  return CHILE_BANNERS[Math.floor(Math.random() * CHILE_BANNERS.length)]
}

// Obtener N banners aleatorios sin repetir
export function getRandomBanners(n = 5) {
  const shuffled = [...CHILE_BANNERS].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(n, CHILE_BANNERS.length))
}

// Obtener banner por ciudad
export function getBannerByCity(city) {
  return CHILE_BANNERS.find(b => b.city.toLowerCase() === city.toLowerCase())
}
